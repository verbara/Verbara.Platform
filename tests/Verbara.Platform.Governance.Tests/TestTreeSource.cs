using System.Runtime.CompilerServices;

namespace Verbara.Platform.Governance.Tests;

/// <summary>
/// Locates the repo's <c>tests/</c> tree (anchored off this file's compile-time path so it works
/// regardless of the working directory or CI layout) and enumerates the real test source files,
/// excluding build output and generated code.
/// </summary>
internal static class TestTreeSource
{
    private const string SolutionFile = "Verbara.Platform.slnx";

    private static readonly string[] GeneratedSuffixes =
    [
        ".g.cs",
        ".Designer.cs",
        ".generated.cs",
    ];

    private static readonly string[] BuildInputExtensions =
    [
        ".cs",
        ".csproj",
        ".props",
        ".targets",
        ".editorconfig",
        ".globalconfig",
    ];

    // Build output and other checkouts; nothing in them configures this tree's build.
    private static readonly string[] NonSourceDirectories =
    [
        "bin",
        "obj",
        "node_modules",
        "TestResults",
        "artifacts",
        ".git",
        ".worktrees",
        ".claude",
    ];

    /// <summary>
    /// Walks parent directories from <paramref name="callerPath"/> until it finds the repo root
    /// (the directory containing <c>Verbara.Platform.slnx</c>) and returns its <c>tests/</c> folder.
    /// Throws if the root cannot be located, so a path regression fails loudly instead of silently
    /// scanning nothing.
    /// </summary>
    public static string TestsRoot([CallerFilePath] string callerPath = "")
    {
        var dir = Directory.GetParent(callerPath);
        while (dir is not null)
        {
            if (File.Exists(Path.Combine(dir.FullName, SolutionFile)))
                return Path.Combine(dir.FullName, "tests");

            dir = dir.Parent;
        }

        throw new InvalidOperationException(
            $"Could not locate '{SolutionFile}' walking up from '{callerPath}'. " +
            "The governance guard cannot find the repo's tests/ tree.");
    }

    /// <summary>The repo root: the parent of <see cref="TestsRoot"/>.</summary>
    public static string RepoRoot() => Directory.GetParent(TestsRoot())!.FullName;

    /// <summary>
    /// Enumerates every file under <paramref name="root"/> that can configure the build: C# sources, MSBuild project
    /// files and analyzer configs. Dotfiles are read on purpose, and the default <see cref="EnumerationOptions"/> would
    /// skip them as hidden. Symlinked directories are not followed. A directory this user cannot read is skipped,
    /// because MSBuild could not read it either.
    /// </summary>
    public static IEnumerable<string> EnumerateBuildInputs(string root)
    {
        var options = new EnumerationOptions { AttributesToSkip = 0, IgnoreInaccessible = true };
        var pending = new Stack<string>();
        pending.Push(root);
        while (pending.TryPop(out var dir))
        {
            foreach (var file in Directory.EnumerateFiles(dir, "*", options).Where(IsBuildInput))
                yield return file;

            foreach (var child in Directory.EnumerateDirectories(dir, "*", options).Where(IsWalkedDirectory))
                pending.Push(child);
        }
    }

    private static bool IsBuildInput(string file) =>
        BuildInputExtensions.Contains(Path.GetExtension(file), StringComparer.OrdinalIgnoreCase);

    private static bool IsWalkedDirectory(string dir) =>
        !NonSourceDirectories.Contains(Path.GetFileName(dir)) && new DirectoryInfo(dir).LinkTarget is null;

    /// <summary>
    /// Enumerates every real test source file under <see cref="TestsRoot"/>, excluding:
    /// any path with an <c>obj</c>/<c>bin</c> segment, generated filenames
    /// (<c>.g.cs</c>/<c>.Designer.cs</c>/<c>.generated.cs</c>), and files whose first 3 lines
    /// carry an <c>&lt;auto-generated</c> banner.
    /// </summary>
    public static IEnumerable<string> EnumerateTestSources()
    {
        var root = TestsRoot();
        foreach (var file in Directory.EnumerateFiles(root, "*.cs", SearchOption.AllDirectories))
        {
            if (HasExcludedSegment(file))
                continue;
            if (HasGeneratedSuffix(file))
                continue;
            if (LooksAutoGenerated(file))
                continue;

            yield return file;
        }
    }

    private static bool HasExcludedSegment(string path)
    {
        var segments = path.Split(Path.DirectorySeparatorChar);
        foreach (var segment in segments)
        {
            if (segment is "obj" or "bin")
                return true;
        }

        return false;
    }

    private static bool HasGeneratedSuffix(string path)
    {
        var fileName = Path.GetFileName(path);
        foreach (var suffix in GeneratedSuffixes)
        {
            if (fileName.EndsWith(suffix, StringComparison.Ordinal))
                return true;
        }

        return false;
    }

    private static bool LooksAutoGenerated(string path)
    {
        using var reader = new StreamReader(path);
        for (var i = 0; i < 3; i++)
        {
            var line = reader.ReadLine();
            if (line is null)
                break;
            if (line.Contains("<auto-generated", StringComparison.Ordinal))
                return true;
        }

        return false;
    }
}
